export type Params = Record<string, string | number>;
/** 表示文言のキーと差し込む値。言語を切り替えたときに描画し直せるよう、文字列ではなくこれで持つ。 */
export type Msg = { k: string; p?: Params };

export const msg = (k: string, p?: Params): Msg => ({ k, p });

/** キー付きのエラー。画面で現在の言語に訳して出す。 */
export class KeyedError extends Error {
  readonly msg: Msg;
  constructor(k: string, p?: Params) {
    super(k);
    this.msg = { k, p };
  }
}

