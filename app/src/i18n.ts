const DICT: Record<Lang, Record<string, string>> = { ja, en };
export const KEYS = Object.keys(ja) as MsgKey[];
export const DICTIONARY = DICT;

/**
 * キーを現在の言語に訳し、{name} に値を差し込む。未知のキーはそのまま返す。
 * "@" で始まる値はそれ自体を文言キーとして訳す（言語を切り替えたときに差し込み値も訳し直すため）。
 */
export function translate(lang: Lang, k: string, p?: Params): string {
  const template = DICT[lang][k] ?? DICT.ja[k] ?? k;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => {
    if (!p || !(name in p)) return `{${name}}`;
    const value = p[name];
    return typeof value === "string" && value.startsWith("@") ? translate(lang, value.slice(1)) : String(value);
  });
}

/** Error / KeyedError / 文字列を、現在の言語の文に直す。 */
export function describeError(lang: Lang, e: unknown): string {
  if (e instanceof KeyedError) return translate(lang, e.msg.k, e.msg.p);
  if (e instanceof Error) return translate(lang, e.message);
  return String(e);
}

export function parseLang(raw: string | null): Lang {
  return raw === "ja" ? "ja" : "en";
}
